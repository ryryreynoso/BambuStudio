import Foundation

/// A pairing document is a credential: import to Keychain, never UserDefaults or logs.
struct RelayPairing: Codable {
    let version: Int
    let name: String
    let lanHost: String
    let relayURL: String
    let token: String

    static func decode(_ data: Data) throws -> RelayPairing {
        guard data.count <= 16_384 else { throw SlicerFailure("This pairing file is too large.") }
        let pairing: RelayPairing
        do { pairing = try JSONDecoder().decode(RelayPairing.self, from: data) }
        catch { throw SlicerFailure("This is not a valid U1 relay pairing file.") }
        guard pairing.version == 1 else { throw SlicerFailure("This pairing file requires a newer app.") }
        try validateToken(pairing.token)
        try PrinterConfig(name: pairing.name, kind: .moonraker, host: pairing.lanHost, relayURL: pairing.relayURL).validate()
        return pairing
    }

    static func validateToken(_ token: String) throws {
        guard (32...512).contains(token.utf8.count), token.utf8.allSatisfy({ (33...126).contains($0) }) else {
            throw SlicerFailure("Use the pairing token generated by your home Mac, without spaces or line breaks.")
        }
    }

    static func read(_ url: URL) throws -> RelayPairing {
        let access = url.startAccessingSecurityScopedResource()
        defer { if access { url.stopAccessingSecurityScopedResource() } }
        let file = try FileHandle(forReadingFrom: url)
        defer { try? file.close() }
        return try decode(file.read(upToCount: 16_385) ?? Data())
    }
}
